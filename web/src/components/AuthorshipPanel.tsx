import { useState } from 'react'
import { useQuery } from '@tanstack/react-query'
import { api } from '../api/client'
import { errorText } from '../api/errors'
import { t } from '../i18n'
import { serverText, valueLabel } from '../i18n/server'

// The log records every column; ids and ordering keys mean nothing to a writer.
const TECHNICAL_FIELD = /(^id$|_id$|sort_key)/
const plain = (value: string) => { const text = value.replace(/_/g, ' '); return text.charAt(0).toUpperCase() + text.slice(1) }

export function AuthorshipPanel({ storyId }: { storyId: string }) {
  const history = useQuery({ queryKey: ['authorship', storyId], queryFn: () => api.getAuthorship(storyId) })
  return <div><h2 id="authorship-title" className="text-xl font-semibold">{t('Who changed this story?')}</h2><p className="writer-help">{t('Changes are attributed to the author, app assistant, or external MCP client. Existing text from before tracking began has unknown authorship; it is not assumed to be yours. Values and provider keys are not stored in this log.')}</p>{history.isPending && <p>{t('Loading…')}</p>}{history.isError && <p role="alert">{errorText(history.error)}</p>}{history.data?.length === 0 && <p className="writer-help">{t('No tracked changes yet.')}</p>}<ul className="authorship-list">{history.data?.filter(entry => !TECHNICAL_FIELD.test(entry.field)).map((entry, index) => <li key={index}><strong>{valueLabel(entry.entity_type)} · {plain(entry.field).toLowerCase()}</strong><span className={`authorship-origin origin-${entry.origin}`}>{serverText(entry.actor_label)}</span><p>{valueLabel(entry.action)} · {new Date(entry.created_at).toLocaleString()}</p></li>)}</ul></div>
}

export function OriginSummary({ storyId, entityId, entityType }: { storyId: string; entityId: string; entityType: string }) {
  const history = useQuery({ queryKey: ['authorship', storyId], queryFn: () => api.getAuthorship(storyId) })
  const latest = history.data?.find(row => row.entity_id === entityId && row.entity_type === entityType)
  return <p className="field-origin-summary">{latest ? <>{t('Latest tracked edit:')}{' '}<span className={`authorship-origin origin-${latest.origin}`}>{serverText(latest.actor_label)}</span>{' '}{t('· {0}. See History → Who wrote what for every change.', latest.field)}</> : t('Authorship unknown until a tracked edit is made.')}</p>
}

type Disclosure = Awaited<ReturnType<typeof api.getDisclosure>>
const day = (value?: string | null) => value ? new Date(value).toLocaleDateString(undefined, { day: 'numeric', month: 'long', year: 'numeric' }) : ''

/** Plain-text AI-use disclosure built from tracked edits; it never claims word percentages. */
function disclosureText(d: Disclosure) {
  const line = (label: string, c: Disclosure['prose']) => `• ${label}: ${c.author} by the author; ${c.mcp + c.assistant} by AI tools (${c.mcp} through connected AI clients, ${c.assistant} by StoryTool's assistant)${c.other ? `; ${c.other} other (scaffolding or undo)` : ''}.`
  return [
    t('AI-use disclosure for “{0}”{1}, generated by StoryTool on {2}.', d.story_title, d.author_name ? ` by ${d.author_name}` : '', day(new Date().toISOString())),
    d.tracking_since ? t('Since tracking began on {0}, StoryTool recorded these saved edits:', day(d.tracking_since)) : t('StoryTool has not recorded any edits yet.'),
    line(t('Manuscript prose'), d.prose),
    line(t('Planning and notes (outline, characters, world)'), d.planning),
    t('AI tools used: {0}.{1}', d.ai_tools.length ? d.ai_tools.join(', ') : 'none recorded', d.last_ai_edit ? ` Last AI edit: ${day(d.last_ai_edit)}.` : ''),
    t('These figures count saved edits, not words, so they do not show how much of the current text each contributor wrote. Text written before tracking began, pasted or imported has unknown origin.'),
  ].join('\n')
}

export function DisclosureCard({ storyId }: { storyId: string }) {
  const summary = useQuery({ queryKey: ['authorship-summary', storyId], queryFn: () => api.getDisclosure(storyId) })
  const [copied, setCopied] = useState(false)
  if (summary.isPending) return <p className="writer-help">{t('Preparing disclosure…')}</p>
  if (summary.isError) return <p role="alert">{errorText(summary.error)}</p>
  const text = disclosureText(summary.data)
  const copy = async () => { try { await navigator.clipboard.writeText(text); setCopied(true); setTimeout(() => setCopied(false), 2000) } catch { setCopied(false) } }
  const download = () => {
    const link = document.createElement('a')
    link.href = URL.createObjectURL(new Blob([text + '\n'], { type: 'text/plain' }))
    link.download = t('{0} - AI-use disclosure.txt', summary.data.story_title || 'story')
    link.click(); URL.revokeObjectURL(link.href)
  }
  return <section className="ui-card mb-4 space-y-2" aria-label={t('AI-use disclosure')}>
    <h3 className="font-semibold">{t('AI-use disclosure')}</h3>
    <p className="writer-help">{t('A plain summary to share with agents, publishers or contests. Check it before sending; it reflects tracked edits only.')}</p>
    <pre className="whitespace-pre-wrap text-sm leading-6">{text}</pre>
    <div className="flex flex-wrap gap-2"><button type="button" className="ui-btn ui-btn-primary" onClick={() => void copy()}>{copied ? t('Copied') : t('Copy text')}</button><button type="button" className="ui-btn ui-btn-secondary" onClick={download}>{t('Download .txt')}</button></div>
  </section>
}
